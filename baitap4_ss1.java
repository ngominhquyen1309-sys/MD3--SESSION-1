public class baitap4_ss1 {
    public static void main (String[] args){
        int a = 7;
        int b = 5;

        int tong = a + b;
        int hieu = a - b;
        int tich = a * b;
        int thuong = a / b;
        int du = a % b;

        System.out.printf("Giá trị a = %d và b = %d%n", a, b);
        System.out.printf("Tổng của a và b = %d%n", tong);
        System.out.printf("Hiệu của a và b = %d%n", hieu);
        System.out.printf("Tích của a và b = %d%n", tich);
        System.out.printf("Thương của a và b = %d%n", thuong);
        System.out.printf("Phần dư của a chia b = %d%n", du);

    }
}
